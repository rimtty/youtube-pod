#!/usr/bin/env python3
"""Apply youtube-pod's local patches to the bundled Python packages.

`scripts/bootstrap.sh` reinstalls `PythonRuntime/site-packages` from
`PythonRuntime/requirements.lock` (with `--upgrade`), so any fix to a vendored
package has to be re-applied after every install. This script is that step.
It is idempotent: already patched files are left alone, pristine upstream
files are patched, and anything else (a partially patched file or an upstream
version whose text no longer matches) fails loudly instead of being skipped.

Patches (see PythonRuntime/patches/README.md for the background):

1. yt-dlp-apple-webkit-jsi: add `webView:decidePolicyForNavigationAction:decisionHandler:`
   to the hidden WKWebView's navigation delegate so script-initiated navigations
   are cancelled instead of being handed to iOS as Universal Links.
2. yt-dlp-ejs: only assign `globalThis.location` when it is undefined, so the
   solver's synthetic YouTube location never becomes a real navigation inside a
   browser-backed runtime. yt-dlp verifies the solver scripts by SHA3-512, so the
   two affected digests in yt-dlp's vendored `_info.py` are recomputed from the
   patched files.

Usage:
    python3 scripts/patch_python_runtime.py          # apply (idempotent)
    python3 scripts/patch_python_runtime.py --check  # verify only, no writes
"""

