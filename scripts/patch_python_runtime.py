# --- Helpers -------------------------------------------------------------------

def read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise PatchError(f"{path} is missing. Run ./scripts/bootstrap.sh first.") from None


def write_atomic(path: Path, text: str) -> None:
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    os.replace(temporary, path)


def sha3_512(path: Path) -> str:
    # Same recipe as yt_dlp.extractor.youtube.jsc._builtin.ejs.Script.hash.
    return hashlib.sha3_512(read(path).encode("utf-8")).hexdigest()


def check_versions() -> None:
    ejs = re.search(r"^__version__ = version = '([^']+)'$", read(SITE_PACKAGES / EJS_VERSION_FILE), re.M)
    plugin = re.search(r"^__version__ = '([^']+)'$", read(SITE_PACKAGES / PLUGIN_VERSION_FILE), re.M)
    found = {
        "yt-dlp-ejs": (ejs.group(1) if ejs else None, EJS_VERSION),
        "yt-dlp-apple-webkit-jsi": (plugin.group(1) if plugin else None, PLUGIN_VERSION),
    }
    mismatches = [f"{name}: found {actual!r}, patches validated against {expected!r}"
                  for name, (actual, expected) in found.items() if actual != expected]
    if mismatches:
        raise PatchError(
            "Upstream package version changed; re-validate the patches in this script "
            "before bumping PythonRuntime/requirements.lock:\n  " + "\n  ".join(mismatches))


def edit_state(text: str, edit: Edit) -> str:
    """Return 'applied' or 'pending' for one edit, or 'unknown'."""
    anchors = text.count(edit.anchor)
    replacements = text.count(edit.replacement)
    # Insertion-style edits keep the anchor inside the replacement, so the
    # anchor legitimately still occurs once after they are applied.
    expected_anchors_when_applied = 1 if edit.anchor in edit.replacement else 0
    if replacements == 1 and anchors == expected_anchors_when_applied:
        return "applied"
    if replacements == 0 and anchors == 1:
        return "pending"
    return "unknown"


def patch_state(text: str, patch: Patch) -> str:
    """Return 'applied' or 'pending'; raise on anything in between."""
    states = [edit_state(text, edit) for edit in patch.edits]
    if all(state == "applied" for state in states):
        return "applied"
    if all(state == "pending" for state in states):
        return "pending"
    raise PatchError(
        f"{patch.path}: unexpected content for '{patch.name}' (edit states {states}). "
        "The upstream file changed or is partially patched; re-run ./scripts/bootstrap.sh "
        "after fixing the anchors in scripts/patch_python_runtime.py.")


def apply_patch(patch: Patch, check: bool) -> str:
    path = SITE_PACKAGES / patch.path
    text = read(path)
    state = patch_state(text, patch)
    if state == "applied":
        return "applied"
    if check:
        return "pending"
    for edit in patch.edits:
        text = text.replace(edit.anchor, edit.replacement, 1)
    if patch_state(text, patch) != "applied":
        raise PatchError(f"{patch.path}: patch '{patch.name}' did not apply cleanly")
    write_atomic(path, text)
    return "patched"


def hash_line_pattern(key: str) -> re.Pattern[str]:
    return re.compile(rf"^(\s*'{re.escape(key)}': ')([0-9a-f]{{128}})(',)$", re.M)


def sync_hashes(check: bool) -> str:
    """Rewrite the two core-script digests in _info.py from the patched files."""
    info_path = SITE_PACKAGES / VENDOR_INFO_FILE
    text = read(info_path)
    expected = {key: sha3_512(SITE_PACKAGES / path) for key, path in CORE_SCRIPTS.items()}

    current: dict[str, str] = {}
    for key in CORE_SCRIPTS:
        matches = hash_line_pattern(key).findall(text)
        if len(matches) != 1:
            raise PatchError(f"{VENDOR_INFO_FILE}: expected exactly one '{key}' entry, found {len(matches)}")
        current[key] = matches[0][1]

    up_to_date = current == expected and HASH_MARKER in text
    if up_to_date:
        return "applied"
    if check:
        if current == UPSTREAM_CORE_HASHES:
            return "pending (pristine upstream hashes)"
        return "pending"

    for key, digest in expected.items():
        text = hash_line_pattern(key).sub(lambda m, d=digest: f"{m.group(1)}{d}{m.group(3)}", text, count=1)
    if HASH_MARKER not in text:
        if HASH_MARKER_ANCHOR not in text:
            raise PatchError(f"{VENDOR_INFO_FILE}: header line not found; cannot place the patch marker")
        text = text.replace(HASH_MARKER_ANCHOR, HASH_MARKER_ANCHOR + HASH_MARKER, 1)
    write_atomic(info_path, text)
    return "patched"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify that every patch is applied; write nothing")
    args = parser.parse_args(argv)

    try:
        check_versions()
        results = [(patch.name, apply_patch(patch, args.check)) for patch in ALL_PATCHES]
        results.append((f"yt-dlp: sync core script digests in {VENDOR_INFO_FILE}", sync_hashes(args.check)))
    except PatchError as error:
        print(f"patch_python_runtime: {error}", file=sys.stderr)
        return 1

    for name, state in results:
        print(f"[{state}] {name}")
    if args.check and any(state != "applied" for _, state in results):
        print("patch_python_runtime: bundled packages are not fully patched. Run ./scripts/bootstrap.sh.",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
